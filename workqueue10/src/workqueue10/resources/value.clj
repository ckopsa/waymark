;; ── the walls ───────────────────────────────────────────────────────

(defn- an-agent?
  "The one predicate the walls below are pure functions of. :system is
  the ENGINE's own actor — a migration, a seed, the conformance walker
  — and is not what either wall is about; they are about the composer."
  [ctx]
  (= :agent (:type (:principal ctx))))

(defn- a-persons-hand?
  "Somebody in this house, as opposed to the composer or the engine.
  `types/actor-types` is #{:human :agent :system} and a scenario may
  spell a member `:person`, so both words for the same hand are named
  here rather than in four places that could drift apart. Asked by the
  affirmation — which is a person's word — and by the observer's own
  wording door, which is not."
  [ctx]
  (contains? #{:human :person} (:type (:principal ctx))))

;; THE AFFIRMATION WALL, GRANTABLE (waymark-sfe, the owner's ruling of
;; 2026-08-28: "It doesn't make sense to disallow it, it just makes
;; sense to permission it"). It used to be a pure function of the
;; principal's kind, refusing every agent outright — a wall standing
;; BESIDE the grants machine even though that machine already spells
;; exactly this scope. It is now `g/unless-granted`, per door, and it
;; says three things instead of one:
;;
;;   a person passes, as ever;
;;   an agent that WROTE this row is refused, grant or no grant —
;;   `:own-field :written_by` is four eyes, and jfv.10's whole point
;;   was that an observer does not answer its own reading;
;;   any other agent passes only under a grant admitting
;;   `value.<this door>` — the owner delegating in his own words.
;;
;; It is minted per action because the refusal NAMES the door a scope
;; would have to admit, and a sentence that said "some door" would
;; send a refused composer to read source.
(defn- affirmation-wall
  "`written-by-a-person`, for one door. jfv.10 left this wall on every
  door that lands a row in `declared` — `still_stands`, `revise`,
  `restore` — and on the `retire`/`dismiss` that take a value out of
  the house's holding. What it guards is the AFFIRMATION rather than
  the writing, which is why `restate` and the create door carry it
  not at all."
  [action]
  (unless-granted
   :value action
   {:name :written-by-a-person
    :own-field :written_by
    :explain "Affirming is a person's word. You may write down what you observed — that row is born observed and says so wherever this house cites it — but marking your own reading affirmed would be speaking in the owner's voice about the owner's own life. Leave it observed and say what you found: publish an insight, cite the rows you read, and offer this value's own \"yes, this one's ours\" as the one next step. The owner answers with a tap, or rewords it himself, and either way the row becomes his."}))

(defguardfn only-the-observer-restates
  {:reads [:principal]
   :explain "This door is the observer's own — it corrects what an agent wrote down while the row is still a guess, and leaves it a guess. Rewording a value is a larger thing when a person does it: those words become this house's law and the row becomes yours in the same stroke. That door is \"Reword\"."}
  [_row _inp ctx]
  ;; the mirror of the wall above, and it exists for the household
  ;; rather than for safety: a person who reached `restate` would be
  ;; editing a value WITHOUT claiming it, which is not a thing anybody
  ;; here wants to do — and because both walls are pure functions of
  ;; the principal, each hand is offered exactly one wording door
  ;; instead of two that look alike. :system passes, for the same
  ;; reason it passes above: the engine's own actor is not the subject.
  (if (a-persons-hand? ctx)
    (t/deny)
    (t/allow)))

(defguardfn a-private-value-is-a-persons-own
  {:judges [:scope]
   :reads [:principal]
   :open "An observer writes what the HOUSE holds; a value scoped \"mine\" is one member's own to declare."
   :explain "A value scoped \"mine\" belongs to the member the engine stamps on it, and the engine stamps the hand that wrote it — so this one would end up yours, about somebody else's life, and the person it is about could never adjust it. Write what you observed as the household's. If it turns out to be one member's alone, he will say so when he claims it."}
  [_row inp ctx]
  ;; the create-door half of `this-is-yours-to-declare`, and the reason
  ;; it had none before jfv.10: a create has no row yet, and while only
  ;; people could write a value `stamp-owner` could only ever name the
  ;; caller. An agent at that door breaks the identity, so the door
  ;; grew a wall rather than the stamp growing a body-supplied owner.
  (if (and (an-agent? ctx) (= "mine" (str (:scope inp))))
    (t/deny)
    (t/allow)))

(defguardfn this-is-yours-to-declare
  {:reads [:principal]
   :explain "This one is somebody else's to say. A value scoped \"mine\" belongs to the member the engine stamped on it; a value the whole house holds is scoped \"household\", and anybody here may write that one."}
  [row _inp ctx]
  ;; reads the ROW rather than storage — a stamped owner is already on
  ;; it — so this stays in the no-database check tier beside the agent
  ;; wall. Absent at create time, deliberately: a create has no row
  ;; yet, and `stamp-owner` writes the caller's own id or nothing, so
  ;; there is no foreign owner a create could name.
  (let [scope (str (get-in row [:data :scope]))
        owner (get-in row [:data :owner])]
    (if (and (= "mine" scope) (not= owner (:id (:principal ctx))))
      (t/deny)
      (t/allow))))

;; ── the stamps ──────────────────────────────────────────────────────

(def authored-fields
  "The surface `revise` overwrites wholesale — the same fields the door
  takes, so what is stored is exactly what was judged. `:scope` and
  `:owner` stay OUT: a value never changes whose law it is, and the
  owner is the engine's stamp rather than anybody's input."
  [:name :says :loved])

(defn- rewritten
  "The authored surface, overwritten wholesale: an omitted optional
  CLEARS, so a value whose loved words are dropped really has none.
  Both wording doors write through here; what separates them is
  whether the landing is an affirmation."
  [row inp]
  (update row :data
          (fn [d] (into d (map (fn [k] [k (get inp k)])) authored-fields))))

(defn- affirmed
  "\"These are my words.\" Who and when, from the engine's own :now and
  principal — never from a body, and never from a clock this file
  reads. Stamped at EVERY door a person's hand lands `declared`
  through, so a reader of rows learns what a reader of transitions
  would: the last time somebody put their name to this sentence."
  [row ctx]
  (-> row
      (assoc-in [:data :affirmed_at] (:now ctx))
      (assoc-in [:data :affirmed_by] (get-in ctx [:principal :id]))))

(defhandler apply-revision [row inp ctx]
  ;; the person's wording door. The transition carries what was written
  ;; (:record true), which is what makes the log the amendment history
  ;; the epic asked for — and the stamp is here because this door lands
  ;; in `declared`: rewording an observed value CLAIMS it, which is the
  ;; owner's own ruling read literally.
  (-> row (rewritten inp) (affirmed ctx)))

(defhandler apply-restatement [row inp _ctx]
  ;; the observer's wording door. The same overwrite and NO stamp: the
  ;; row is still a guess when this handler is done with it, which is
  ;; the whole difference between the two doors.
  (rewritten row inp))

(defhandler stamp-the-affirmation [row _inp ctx]
  ;; the tap, and the restore. Nothing about the words changes; what
  ;; changes is whose they are.
  (affirmed row ctx))

(defn- stamp-the-writer
  "Whose hand wrote this row down — ANY principal, agent or person,
  written by the ENGINE and never trusted from the body (`insight`'s
  `authored_by` and `outcome`'s `composed_by`, one kind over).

  It is deliberately NOT `owner`, which answers a different question:
  `owner` is whose value it is (the \"mine\" scoping), `written_by` is
  who noticed. jfv.10 needed both to be sayable at once, and neither
  `observed_by` nor `declared_by` could be said honestly about the
  other hand's rows — `written_by` is true of both."
  [row ctx]
  (assoc-in row [:data :written_by] (:id (:principal ctx))))

(defn- stamp-owner
  "Whose law this is, written by the ENGINE and never trusted from the
  body (feed_recipe's `stamp-owner`, one kind over). A \"mine\" value
  is the writer's own — a person cannot put words in somebody else's
  mouth by naming them in a form — and a \"household\" value is nobody's
  in particular, so it carries no owner at all.

  `a-private-value-is-a-persons-own` stands in front of it, so the
  writer here is always a person when the scope is \"mine\"."
  [row ctx]
  (assoc-in row [:data :owner]
            (when (= "mine" (str (get-in row [:data :scope])))
              (:id (:principal ctx)))))

(defn- born
  "The birth state, and the birth stamps. A person declaring a value
  has already decided, so his lands `declared` and is affirmed in the
  same breath; anybody else's lands `observed` — the initial — and
  says so wherever this house cites it until a person's hand moves it.

  The engine's own actors (a seed, a migration, the conformance
  walker) land `observed` too, and that is the point of the default
  rather than an oversight: a row nobody's hand can be found on is a
  guess, and a guess is the safe direction for this to fail in."
  [row ctx]
  (let [row (-> row (stamp-owner ctx) (stamp-the-writer ctx))]
    (if (a-persons-hand? ctx)
      (-> row (assoc :state :declared) (affirmed ctx))
      row)))

