(ns workqueue10.resources.value
  "The value (waymark-jfv.2, reshaped by waymark-jfv.10): what this
  house actually cares about — written down by the person who cares
  about it, or OBSERVED by an agent that read the house and affirmed
  by him afterwards.

  The owner's own words are the whole reason this kind exists:

    Use AI to create a menu of outcomes aligned with my values, and
    reduce the friction of reaching them by aligning the actions with
    the activities I love.

  And the sharper claim underneath them, which is what the row is
  shaped by: TIME FOLLOWS THE FRICTION GRADIENT ACROSS VALUES, NOT THE
  VALUES THEMSELVES. Building with AI is cheap to start and wins the
  evening; making memories with the family is valued MORE and costs
  more to begin. A house that only ever showed itself what was true
  would lose that contest every night, because the truth is that the
  cheap thing is cheap. So the declaration comes first: `making
  memories with the family`, `Grandpa is cared for`, `building` — each
  one beside the activities he LOVES, because a value with no loved
  activity next to it is precisely the high-friction value the whole
  thesis is about.

  VALUES ARE LEARNED IN THE OPEN (waymark-jfv.10, and it overrules
  this file's first law). jfv.2 walled every door here against agents
  — declared is law, learned is evidence that files asks — and the
  owner overruled it in his own words on 2026-08-25:

    Discovering what you value and what you love to do is a process
    and there's nothing wrong with you learning what my values are
    and writing them to waymark — just so long as I can adjust them
    too.

  So the wall moved rather than fell, and it moved to the honest
  place. AN AGENT MAY WRITE WHAT IT OBSERVES; ONLY A PERSON AFFIRMS
  IT. Those are two facts about one row and the machine says both:
  a value an agent writes is born `observed` and SAYS SO wherever it
  is cited — its own summary line, and the sentence on every outcome
  card that spends a week on it. A value a person writes is born
  `declared`, because a person declaring one has already decided.
  What moves the row from the first to the second is a person's own
  hand: the `still_stands` tap, a `revise`, or a `restore`.

  THE AFFIRMATION IS A STATE, NOT A STAMP, and the weighing is worth
  keeping because the stamp was the cheaper answer. A stamp
  (`affirmed_by`/`affirmed_at` alone, the `reviewed_by` shape jfv.2
  already had) would have kept ONE `revise` door and cost nothing.
  It loses on the requirement that decides this bead — that an
  unaffirmed value SAY so wherever it is cited. `summary/render` has
  no conditional: a missing field renders an em-dash, never a
  sentence, so a row's own summary cannot speak a stamp's absence.
  A state speaks on every envelope, every list line, every card
  summary and every transition record; `:filterable :state` already
  exists, so `what has been observed and not yet affirmed` is a query
  this house already owns; the affirmation becomes a TRANSITION,
  which is how the row shows both hands; and `outcome/names-a-value`
  and `feed/value-still-held?` already read state, so admitting an
  observed value widens a check rather than adding a field read.

  ITS COST, PAID HERE IN THE OPEN: `:to` is a static keyword, so one
  door cannot land in two states. A single `revise` open to both
  hands would have had an agent's own rewording land in `declared` —
  the observer affirming its own guess, which is the one thing this
  bead exists to forbid. So the wording door SPLITS by hand, and the
  split reads as what it is: `revise` is a person's, lands in
  `declared`, and rewording an observed value CLAIMS it in the same
  stroke; `restate` is the observer's, runs `observed → observed`,
  and never leaves the record of what was noticed. Each hand sees
  exactly one of them, because both walls read the principal and the
  presented leash, and the render probe reads the same two facts the
  invoke does.

  AND THE AFFIRMATION WALL IS GRANTABLE (waymark-sfe, 2026-08-28). The
  owner ruled a second time, on the wall itself rather than on the
  writing: \"The whole reason we have the access controls we have is so
  that I can ask you to do what I want when I want. It doesn't make
  sense to disallow it, it just makes sense to permission it.\" So
  `written-by-a-person` no longer refuses every agent — it refuses one
  that presents no grant admitting the door it is knocking on
  (`value.still_stands`, `value.revise`, …), and it refuses the agent
  that WROTE the row whatever it presents. Nothing above changes: an
  agent's own reading is still not an affirmation, because affirming
  it would be answering its own guess. What changed is that the OWNER
  may hand a delegate his own yes, through the approval_request door,
  and read afterwards which grant it acted under.

  THE PETITION STILL STANDS, and it is now the second thing
  `still_stands` does rather than the only one. The epic asks for
  learned signals to petition an amendment only the owner ratifies.
  The door for `an agent says something with evidence and offers a
  next step` is the insight, and its create wall
  `offers-something-light` refuses any offered action heavier than
  `selection`, while `demand/field-class` reads EVERY plain string as
  recall. Every door that could take a new wording takes a string. So
  no petition can offer the amendment itself: `still_stands` asks for
  nothing, renders `assent`, and is therefore a legal insight offer —
  the tap means `yes, this one is ours`, and the REWORDING is the
  owner's own `revise`, on this row, through this row's own screen.

  `still_stands` IS NOT A HOLLOW TAP, and that is worth saying out
  loud because it looks like one. On an observed row it is the whole
  affirmation. On a declared row it is the other fact: an unanswered
  petition and a read-but-unchanged declaration are different things,
  and the second is the most useful thing a composer can learn — THE
  OWNER READ THE EVIDENCE AND THE VALUE STANDS ANYWAY, which means
  the friction is in the plan and not in the declaration.
  `affirmed_by` and `affirmed_at` are that fact on the row itself,
  stamped by the engine at every door a person's hand lands
  `declared` through, so a reader of rows learns what a reader of
  transitions would.

  A one-tap ratification of an EXACT proposed wording wants waymark-0k4's
  staged proposal generalized past `feed_recipe`; that is the other
  half of waymark-xw3 and it is filed rather than built.

  LOVED ACTIVITIES ARE FREE WORDS, AND THAT SET IS THE VOCABULARY.
  Two alternatives were weighed and both lose. Linking to
  eveningplan10's `activity` kind borrows another domain's nouns for a
  word like `the shop`. Minting a `loved_activity` kind is a row per
  word — a noun for a noun's sake. The household's own sentence — `I
  love the shop, I love building with the boys, I love cooking with a
  podcast on` — IS the declaration, and what those words buy
  downstream is a checkable citation: a plan's routing, when it names
  a loved activity, must match a word some declared value carries, and
  the refusal narrates the legal words. There is no picker, and there
  will not be one until a row-backed `x-options` source exists
  (waymark-90k); a guard and a good sentence is this tree's usual
  first answer anyway.

  :nav :secondary IS LOAD-BEARING AND IS NOT COSMETIC. `next_actions`
  claims the OPEN rows of every :nav :primary kind, and `fuel` speaks
  only about :nav :primary kinds. A value is permanently open by
  construction — `declared` is where it lives, not where it waits, and
  `observed` is a standing rather than a queue either — so
  a :primary value would card in do-now forever and a retired one
  would be congratulated as a deed. `feed_recipe` is :secondary for
  exactly this reason. (Hand-written kinds inherit no :nav: the
  :decision sugar is what hands tickler and insight :system for free,
  and the sugar cannot spell this kind — a value is long-lived law,
  not a one-shot verdict.)

  SCOPE IS feed_recipe'S, VERBATIM. `household` or `mine`, with the
  owner STAMPED BY THE ENGINE and never trusted from the body. The
  wall that matters is the stamp rather than concealment:
  `this-is-yours-to-declare` refuses a `mine` value to anyone but its
  owner, and a `household` value is any adult's to write — the
  deviation waymark-4yn already recorded for the household recipe. A
  second pair of eyes on a household value is waymark-pcr's question
  and is not re-decided here.

  AND THE HOLE THE RULING OPENED IN IT, CLOSED BY ITS OWN WALL. The
  owner stamp is the WRITER's id, so an agent writing a `mine` value
  would own a sentence about somebody else's life — and
  `this-is-yours-to-declare` would then refuse the very person whose
  value it is, which breaks the one condition the ruling attached
  (`just so long as I can adjust them too`). So
  `a-private-value-is-a-persons-own` stands at the create door: what
  an observer notices, it writes as the HOUSE's, and if it turns out
  to be one member's alone he says so when he claims it. Every
  `observed` row in this engine is therefore `household`-scoped by
  construction, which is why the doors that only observed rows reach
  carry no ownership wall.

  THE SMALLEST HONEST MACHINE, ONE STATE LARGER THAN jfv.2's.
  `observed`, `declared`, `retired`; none terminal; `observed` is the
  initial and a person's create promotes out of it in the same
  transaction. THE DEFAULT IS THE UNAFFIRMED ONE ON PURPOSE — a birth
  nobody's hand can be found on reads as a guess, which is the safe
  direction for a bug to fail in. `:on-create` branching the birth
  state is the framework's own spelling (`definitions`: a held
  revision is born `:proposed`).

  There is still no `proposed`, because `observed` is what that state
  would have meant and it now has an honest name; and still no
  `amended`, because an amendment is a REVISION of a standing law and
  not a different state of it — the row's own transitions are the
  record of who changed what, when, and from which law revision.
  Retiring is how a house stops hearing about an outcome for good, and
  it is the only honest way: the outcomes that serve a retired value
  stop being staged. A retired value comes back `declared` rather than
  `observed`, because a person reaching for `restore` has held it
  again with his own hand."
