(defn- an-agent?
  "The one predicate the walls below are pure functions of. :system is
  the ENGINE's own actor — a migration, a seed, the conformance walker
  — and is not what either wall is about; they are about the composer."
  [ctx]
  (= :agent (:type (:principal ctx))))

;; THE AFFIRMATION WALL, GRANTABLE (waymark-sfe, the owner's ruling of
;; 2026-08-28: "It doesn't make sense to disallow it, it just makes
;; sense to permission it"). It used to be a pure function of the
;; principal's kind, refusing every agent outright — a wall standing
;; BESIDE the grants machine even though that machine already spells
;; exactly this scope. It is now `g/unless-granted`, per door, and it
;; says three things instead of one:
;;
;;   a person passes, as ever;
;;   an agent that WROTE this row is refused, grant or no grant —
;;   `:own-field :written_by` is four eyes, and jfv.10's whole point
;;   was that an observer does not answer its own reading;
;;   any other agent passes only under a grant admitting
;;   `value.<this door>` — the owner delegating in his own words.
;;
;; It is minted per action because the refusal NAMES the door a scope
;; would have to admit, and a sentence that said "some door" would
;; send a refused composer to read source.
(defn- affirmation-wall
  "`written-by-a-person`, for one door. jfv.10 left this wall on every
  door that lands a row in `declared` — `still_stands`, `revise`,
  `restore` — and on the `retire`/`dismiss` that take a value out of
  the house's holding, and left it OFF the create door because a
  create landed `observed` and affirmed nothing.

  IT IS ON THE CREATE DOOR AS OF waymark-bug (2026-08-31), and the
  reason is arithmetic rather than a change of heart: `observed` went
  to the hypothesis kind, so there is no unaffirmed landing left and
  EVERY create is now an affirmation. The wall did not move; the
  states moved out from under it. What an agent writes instead is an
  INTENT HYPOTHESIS — the same sentence, with a prior, a posterior and
  the atoms that moved it — and the refusal below says so by name."
  [action]
  (unless-granted
   :value action
   {:name :written-by-a-person
    :own-field :written_by
    :explain "Declaring a value is a person's word, and since the belief layer landed there is no half-way state for one: a value in this house is law, so writing one would be speaking in the owner's voice about the owner's own life. What you noticed goes in an INTENT HYPOTHESIS instead — POST /api/hypotheses with shape \"intent\", the claim in your words, this house's rows as what it is about, and where you honestly think the guess starts. That row is born observed, says so wherever it is cited, and carries a number that moves as the findings land. The owner answers it with a tap, and putting it in his own words on a value is his."}))

(defguardfn a-private-value-is-a-persons-own
  {:judges [:scope]
   :reads [:principal]
   :open "An observer writes what the HOUSE holds; a value scoped \"mine\" is one member's own to declare."
   :explain "A value scoped \"mine\" belongs to the member the engine stamps on it, and the engine stamps the hand that wrote it — so this one would end up yours, about somebody else's life, and the person it is about could never adjust it. Write what you observed as the household's. If it turns out to be one member's alone, he will say so when he claims it."}
  [_row inp ctx]
  ;; the create-door half of `this-is-yours-to-declare`, and the reason
  ;; it had none before jfv.10: a create has no row yet, and while only
  ;; people could write a value `stamp-owner` could only ever name the
  ;; caller. An agent at that door breaks the identity, so the door
  ;; grew a wall rather than the stamp growing a body-supplied owner.
  (if (and (an-agent? ctx) (= "mine" (str (:scope inp))))
    (t/deny)
    (t/allow)))

(defguardfn this-is-yours-to-declare
  {:reads [:principal]
   :explain "This one is somebody else's to say. A value scoped \"mine\" belongs to the member the engine stamped on it; a value the whole house holds is scoped \"household\", and anybody here may write that one."}
  [row _inp ctx]
  ;; reads the ROW rather than storage — a stamped owner is already on
  ;; it — so this stays in the no-database check tier beside the agent
  ;; wall. Absent at create time, deliberately: a create has no row
  ;; yet, and `stamp-owner` writes the caller's own id or nothing, so
  ;; there is no foreign owner a create could name.
  (let [scope (str (get-in row [:data :scope]))
        owner (get-in row [:data :owner])]
    (if (and (= "mine" scope) (not= owner (:id (:principal ctx))))
      (t/deny)
      (t/allow))))

