(def authored-fields
  "The surface `revise` overwrites wholesale — the same fields the door
  takes, so what is stored is exactly what was judged. `:scope` and
  `:owner` stay OUT: a value never changes whose law it is, and the
  owner is the engine's stamp rather than anybody's input."
  [:name :says :loved])

(defn- rewritten
  "The authored surface, overwritten wholesale: an omitted optional
  CLEARS, so a value whose loved words are dropped really has none.
  Both wording doors write through here; what separates them is
  whether the landing is an affirmation."
  [row inp]
  (update row :data
          (fn [d] (into d (map (fn [k] [k (get inp k)])) authored-fields))))

(defn- affirmed
  "\"These are my words.\" Who and when, from the engine's own :now and
  principal — never from a body, and never from a clock this file
  reads. Stamped at EVERY door a person's hand lands `declared`
  through, so a reader of rows learns what a reader of transitions
  would: the last time somebody put their name to this sentence."
  [row ctx]
  (-> row
      (assoc-in [:data :affirmed_at] (:now ctx))
      (assoc-in [:data :affirmed_by] (get-in ctx [:principal :id]))))

(defhandler apply-revision [row inp ctx]
  ;; the person's wording door. The transition carries what was written
  ;; (:record true), which is what makes the log the amendment history
  ;; the epic asked for — and the stamp is here because this door lands
  ;; in `declared`: rewording an observed value CLAIMS it, which is the
  ;; owner's own ruling read literally.
  (-> row (rewritten inp) (affirmed ctx)))

(defhandler stamp-the-affirmation [row _inp ctx]
  ;; the tap, and the restore. Nothing about the words changes; what
  ;; changes is whose they are.
  (affirmed row ctx))

(defn- stamp-the-writer
  "Whose hand wrote this row down — ANY principal, agent or person,
  written by the ENGINE and never trusted from the body (`insight`'s
  `authored_by` and `outcome`'s `composed_by`, one kind over).

  It is deliberately NOT `owner`, which answers a different question:
  `owner` is whose value it is (the \"mine\" scoping), `written_by` is
  who noticed. jfv.10 needed both to be sayable at once, and neither
  `observed_by` nor `declared_by` could be said honestly about the
  other hand's rows — `written_by` is true of both."
  [row ctx]
  (assoc-in row [:data :written_by] (:id (:principal ctx))))

(defn- stamp-owner
  "Whose law this is, written by the ENGINE and never trusted from the
  body (feed_recipe's `stamp-owner`, one kind over). A \"mine\" value
  is the writer's own — a person cannot put words in somebody else's
  mouth by naming them in a form — and a \"household\" value is nobody's
  in particular, so it carries no owner at all.

  `a-private-value-is-a-persons-own` stands in front of it, so the
  writer here is always a person when the scope is \"mine\"."
  [row ctx]
  (assoc-in row [:data :owner]
            (when (= "mine" (str (get-in row [:data :scope])))
              (:id (:principal ctx)))))

(defn- born
  "The birth stamps, and the affirmation that now rides every one of
  them (waymark-bug, 2026-08-31). While this kind had an `observed`
  state the birth BRANCHED: a person's create landed `declared` and
  was affirmed in the same breath, anybody else's landed `observed`
  and said so until a hand moved it. There is no `observed` any more —
  it went to the hypothesis kind, which is the same one bit of belief
  with arithmetic and atoms under it — so there is no unaffirmed
  landing left to branch INTO, and every value is born the house's
  law.

  Which is why the wall came back to the create door
  (`(affirmation-wall :create)`): with nowhere unaffirmed to land, an
  agent writing a value would be affirming its own reading, and that
  is the one thing jfv.10 forbade while it was widening everything
  else. It came back GRANTABLE rather than absolute, per waymark-sfe,
  so the owner may still hand a delegate his own hand and read
  afterwards which grant it acted under.

  `:system` — a seed, a migration, the conformance walker — passes the
  wall and is stamped like anybody else. That is a change of direction
  from jfv.10, where the safe failure was `observed`; with the state
  gone the safe failure is a REFUSAL, and the engine's own actor is
  not who the wall is about."
  [row ctx]
  (-> row (stamp-owner ctx) (stamp-the-writer ctx) (affirmed ctx)))

